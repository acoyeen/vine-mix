"""Generate libsamplerate 0.2.2's SRC_SINC_FASTEST coefficients for Rust.

Input: third_party/src/libsamplerate-0.2.2/src/fastest_coeffs.h (pinned,
hash-verified archive). Output: crates/vinemix-resample/src/fastest_coeffs.rs.

The C table stores double-precision decimal literals in a `float` array, so a
compiler rounds each one twice (decimal -> binary64 -> binary32). That rule is
reproduced exactly with rational arithmetic.
"""

from __future__ import annotations

import re
import struct
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "third_party/src/libsamplerate-0.2.2/src/fastest_coeffs.h"
TARGET = ROOT / "crates/vinemix-resample/src/fastest_coeffs.rs"


def round_to_binary(value: Fraction, mantissa_bits: int, min_exp: int) -> Fraction:
    if value == 0:
        return Fraction(0)
    sign = -1 if value < 0 else 1
    value = abs(value)
    exponent = value.numerator.bit_length() - value.denominator.bit_length()
    if Fraction(2) ** exponent > value:
        exponent -= 1
    exponent = max(exponent, min_exp)
    quantum = Fraction(2) ** (exponent - mantissa_bits)
    scaled = value / quantum
    floor = scaled.numerator // scaled.denominator
    remainder = scaled - floor
    if remainder > Fraction(1, 2) or (remainder == Fraction(1, 2) and floor % 2 == 1):
        floor += 1
    return sign * floor * quantum


def double_literal_as_f32(token: str) -> int:
    exact = Fraction(token)
    if exact == 0:
        return 0x80000000 if token.startswith("-") else 0
    as_double = round_to_binary(exact, 52, -1022)
    as_single = round_to_binary(as_double, 23, -126)
    return struct.unpack("<I", struct.pack("<f", float(as_single)))[0]


def main() -> None:
    text = re.sub(r"/\*.*?\*/", "", SOURCE.read_text(), flags=re.S)
    body = re.search(r"fastest_coeffs\s*=\s*\{\s*(\d+)\s*,\s*\{(.*?)\}\s*\}\s*;", text, re.S)
    increment = int(body.group(1))
    tokens = [t for t in re.split(r"[\s,]+", body.group(2)) if t]
    assert len(tokens) == 2464, len(tokens)
    lines = [
        "//! libsamplerate 0.2.2 `fastest_coeffs.h` (SRC_SINC_FASTEST), generated by",
        "//! tools/generate-samplerate-coeffs.py. Copyright Erik de Castro Lopo,",
        "//! 2-clause BSD (see licenses/libsamplerate-COPYING.txt). Do not edit.",
        "",
        "#![allow(clippy::unreadable_literal)]",
        "",
        f"pub const INCREMENT: i32 = {increment};",
        "",
        "pub static COEFFS: [f32; 2464] = [",
    ]
    lines += [f"    f32::from_bits(0x{double_literal_as_f32(t):08x})," for t in tokens]
    lines.append("];")
    TARGET.write_text("\n".join(lines) + "\n", newline="\n")
    print(f"{len(tokens)} coefficients, increment {increment}")


if __name__ == "__main__":
    main()
