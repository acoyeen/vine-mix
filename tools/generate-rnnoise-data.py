"""Generate the RNNoise v0.2 tables and model blob used by vinemix-denoise.

Inputs are the pinned, hash-verified upstream archives extracted under
third_party/src (see scripts/fetch-reference-sources.ps1):

  rnnoise-0.2/src/rnnoise_tables.c   FFT bit-reverse/twiddles, window, DCT
  src/rnnoise_data.c                 model 0b50c45 (rnnoise_data-0b50c45.tar.gz)

Outputs (committed, reproducible):

  crates/vinemix-denoise/src/rnnoise/tables.rs
  crates/vinemix-denoise/model/rnnoise-0b50c45.bin

C compilers round each float literal exactly once when it has an `f` suffix
(decimal -> binary32) and twice when it does not (decimal -> binary64 ->
binary32). Both rules are reproduced exactly with rational arithmetic, so the
Rust tables hold bit-identical values to the C objects.

Only the arrays the floating-point inference path reads are exported: float
weights, sparse indices, biases and GRU diagonals. The int8 copies, scales and
SU biases are used only by the quantised path, which upstream never selects
while float weights are present.
"""

from __future__ import annotations

import re
import struct
import sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TABLES_C = ROOT / "third_party/src/rnnoise-0.2/src/rnnoise_tables.c"
DATA_C = ROOT / "third_party/src/src/rnnoise_data.c"
TABLES_RS = ROOT / "crates/vinemix-denoise/src/rnnoise/tables.rs"
MODEL_BIN = ROOT / "crates/vinemix-denoise/model/rnnoise-0b50c45.bin"


def round_to_binary(value: Fraction, mantissa_bits: int, min_exp: int) -> Fraction:
    """Round an exact rational to the nearest IEEE value (ties to even)."""
    if value == 0:
        return Fraction(0)
    sign = -1 if value < 0 else 1
    value = abs(value)
    exponent = value.numerator.bit_length() - value.denominator.bit_length()
    if Fraction(2) ** exponent > value:
        exponent -= 1
    exponent = max(exponent, min_exp)
    quantum = Fraction(2) ** (exponent - mantissa_bits)
    scaled = value / quantum
    floor = scaled.numerator // scaled.denominator
    remainder = scaled - floor
    if remainder > Fraction(1, 2) or (remainder == Fraction(1, 2) and floor % 2 == 1):
        floor += 1
    return sign * floor * quantum


def f32_bits(value: Fraction) -> int:
    rounded = round_to_binary(value, 23, -126)
    return struct.unpack("<I", struct.pack("<f", float(rounded)))[0]


def literal_bits(token: str) -> int:
    token = token.strip()
    single = token.endswith(("f", "F"))
    text = token[:-1] if single else token
    exact = Fraction(text)
    if exact == 0:
        return 0x80000000 if text.startswith("-") else 0
    if single:
        return f32_bits(exact)
    as_double = round_to_binary(exact, 52, -1022)
    return f32_bits(as_double)


def c_array(source: str, name: str) -> list[str]:
    match = re.search(r"\b" + re.escape(name) + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", source, re.S)
    if not match:
        raise SystemExit(f"array {name} not found")
    body = re.sub(r"/\*.*?\*/", "", match.group(1), flags=re.S)
    return [token for token in re.split(r"[\s,{}]+", body) if token]


def rust_f32(bits: int) -> str:
    return f"f32::from_bits(0x{bits:08x})"


def generate_tables() -> None:
    source = TABLES_C.read_text()
    bitrev = [int(token) for token in c_array(source, "fft_bitrev")]
    twiddles = [literal_bits(token) for token in c_array(source, "fft_twiddles")]
    window = [literal_bits(token) for token in c_array(source, "rnn_half_window")]
    dct = [literal_bits(token) for token in c_array(source, "rnn_dct_table")]
    assert len(bitrev) == 960 and len(twiddles) == 1920 and len(window) == 480 and len(dct) == 1024
    factors = re.search(r"\{([0-9, ]+)\},\s*/\* factors \*/", source).group(1)
    scale = re.search(r"\n([0-9.e+-]+f), /\* scale \*/", source).group(1)
    lines = [
        "//! RNNoise v0.2 lookup tables, generated by tools/generate-rnnoise-data.py",
        "//! from the pinned upstream `rnnoise_tables.c` (BSD licence, see",
        "//! licenses/RNNoise-COPYING.txt). Do not edit by hand.",
        "",
        "#![allow(clippy::unreadable_literal, clippy::approx_constant)]",
        "",
        f"pub const FFT_SCALE: f32 = {rust_f32(literal_bits(scale))};",
        f"pub const FFT_FACTORS: [usize; 10] = [{', '.join(factors.split(',')[:10])}];",
        "",
        f"pub static FFT_BITREV: [u16; 960] = [{', '.join(map(str, bitrev))}];",
        "",
        "/// `(re, im)` twiddle factors.",
        "pub static FFT_TWIDDLES: [(f32, f32); 960] = [",
    ]
    for k in range(960):
        lines.append(f"    ({rust_f32(twiddles[2 * k])}, {rust_f32(twiddles[2 * k + 1])}),")
    lines.append("];")
    lines.append("")
    lines.append("pub static HALF_WINDOW: [f32; 480] = [")
    lines += [f"    {rust_f32(bits)}," for bits in window]
    lines.append("];")
    lines.append("")
    lines.append("pub static DCT_TABLE: [f32; 1024] = [")
    lines += [f"    {rust_f32(bits)}," for bits in dct]
    lines.append("];")
    TABLES_RS.write_text("\n".join(lines) + "\n", newline="\n")


EXPORTED = re.compile(r"_(weights_float|weights_idx|bias|recurrent_weights_diag)$")


def generate_model() -> None:
    source = DATA_C.read_text()
    arrays = re.findall(r"static const (float|int) (\w+)\[(\d+)\] = \{(.*?)\};", source, re.S)
    out = bytearray(b"VMRN")
    selected = [(kind, name, int(size), body) for kind, name, size, body in arrays
                if EXPORTED.search(name) and not name.endswith("_subias")]
    out += struct.pack("<II", 1, len(selected))
    for kind, name, size, body in selected:
        tokens = [token for token in re.split(r"[\s,]+", body) if token]
        assert len(tokens) == size, name
        encoded = name.encode()
        out += struct.pack("<B", len(encoded)) + encoded
        if kind == "float":
            out += struct.pack("<BI", 0, size)
            out += struct.pack(f"<{size}I", *[literal_bits(token) for token in tokens])
        else:
            out += struct.pack("<BI", 1, size)
            out += struct.pack(f"<{size}i", *[int(token) for token in tokens])
    MODEL_BIN.parent.mkdir(parents=True, exist_ok=True)
    MODEL_BIN.write_bytes(bytes(out))
    print(f"{len(selected)} arrays, {len(out)} bytes")


if __name__ == "__main__":
    generate_tables()
    generate_model()
    sys.exit(0)
